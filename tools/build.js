// Bundles src/*.js into docs/pebble.js (for the browser) and examples/*.pb into docs/examples.js.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const order = ['errors', 'lexer', 'parser', 'interpreter', 'index'];

let bundle = '/* Pebble language - generated by tools/build.js from src/. Do not edit by hand. */\n(function (global) {\n  var defs = {}, cache = {};\n  function req(name) {\n    name = name.replace("./", "");\n    if (!cache[name]) { var m = { exports: {} }; cache[name] = m; defs[name](m, m.exports, req); }\n    return cache[name].exports;\n  }\n';
for (const name of order) {
  const code = fs.readFileSync(path.join(root, 'src', name + '.js'), 'utf8');
  bundle += `  defs[${JSON.stringify(name)}] = function (module, exports, require) {\n${code}\n  };\n`;
}
bundle += '  global.Pebble = req("index");\n})(typeof self !== "undefined" ? self : this);\n';
fs.writeFileSync(path.join(root, 'docs', 'pebble.js'), bundle);

const ex = {};
for (const f of fs.readdirSync(path.join(root, 'examples')).sort()) {
  if (f.endsWith('.pb')) ex[f.replace('.pb', '')] = fs.readFileSync(path.join(root, 'examples', f), 'utf8');
}
fs.writeFileSync(path.join(root, 'docs', 'examples.js'), 'window.PEBBLE_EXAMPLES = ' + JSON.stringify(ex, null, 2) + ';\n');
console.log('built docs/pebble.js and docs/examples.js');
